"""
scripts/build/generate_yaml.py
──────────────────────────────────
Stage 5.9 YAML Generation: writes dataset/final/data.yaml for YOLOv8s
training. Mechanical — matches config/classes.yaml's schema exactly
(nc: 16, names in config_loader.CANONICAL_NAMES order), and matches
config/training.yaml's existing `data: dataset/final/data.yaml` reference
(already written, pointing here before this script existed).

train/val/test paths must resolve relative to the yaml file's own
directory (dataset/final/), not an absolute machine-specific path —
training happens on RunPod (cloud GPU, PLAN.md Phase 3 / DEC-026), not
this machine, so an absolute local path would need editing anyway; a
relative one works as long as dataset/final/'s contents travel with the
yaml.

The `path` key is deliberately OMITTED, not set to ".", to actually get
that behavior (DEC-066 code-review finding, verified against the real
installed ultralytics package, not assumed): `check_det_dataset()`
resolves an explicit `path` value relative to the training process's
CURRENT WORKING DIRECTORY (or as an absolute path), never relative to
the yaml file itself — `path: "."` would resolve `train: train/images`
to `<cwd>/train/images`, not `<cwd>/dataset/final/train/images`, silently
breaking training if invoked from anywhere other than dataset/final/
itself. Omitting `path` lets ultralytics fall through to its own
documented fallback, `Path(data["yaml_file"]).parent` — the yaml's own
directory — which is what "relative, travels with the yaml" actually
requires. Verified end-to-end via `ultralytics.data.utils.check_det_dataset`
against the real generated file from a CWD other than dataset/final/.

Verifies dataset/final/{train,val,test}/images+labels actually exist and
are non-empty before writing — a data.yaml pointing at empty or missing
directories would fail loudly at training time instead of now.

Usage:
    python3 scripts/build/generate_yaml.py
    python3 scripts/build/generate_yaml.py --dry-run
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

# Leaf script, not a shared library module — needs the repo root on
# sys.path to import sibling utils regardless of how it's invoked.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import yaml  # noqa: E402

from scripts.utils.config_loader import get_canonical_names, load_classes  # noqa: E402
from scripts.utils.file_utils import final_dir  # noqa: E402

OUTPUT_PATH_RELATIVE = "dataset/final/data.yaml"  # matches config/training.yaml's existing `data:` reference


def run(dry_run: bool = False) -> dict[str, Any]:
    classes = load_classes()
    nc = classes["nc"]
    names = get_canonical_names()

    split_counts = {}
    empty_splits = []
    for split in ("train", "val", "test"):
        images_dir = final_dir(split) / "images"
        labels_dir = final_dir(split) / "labels"
        n_images = len(list(images_dir.glob("*"))) if images_dir.is_dir() else 0
        n_labels = len(list(labels_dir.glob("*.txt"))) if labels_dir.is_dir() else 0
        split_counts[split] = {"images": n_images, "labels": n_labels}
        print(f"  {split}: images={n_images} labels={n_labels}")
        if n_images == 0:
            empty_splits.append(split)
            print(f"  WARNING: dataset/final/{split}/images/ is empty — run scripts/build/split.py (Stage 5.8) first.")

    # Gate, not just warn — a data.yaml pointing at an empty split must fail loudly
    # now, not produce a file that looks complete and only fails at training time
    # (the module docstring's own stated goal). --dry-run still previews regardless,
    # since its purpose is showing what WOULD be written.
    if empty_splits and not dry_run:
        raise FileNotFoundError(
            f"Refusing to write data.yaml: {empty_splits} split(s) are empty. "
            f"Run scripts/build/split.py (Stage 5.8) first, or pass --dry-run to preview anyway."
        )

    data_yaml = {
        # No "path" key — see module docstring. ultralytics resolves an explicit
        # `path` relative to the training process's CWD, not the yaml's own
        # directory; omitting it lets check_det_dataset() fall through to
        # Path(yaml_file).parent instead, which is what we actually need.
        "train": "train/images",
        "val": "val/images",
        "test": "test/images",
        "nc": nc,
        "names": {i: name for i, name in enumerate(names)},
    }

    if dry_run:
        print("\n--dry-run: would write:")
        print(yaml.safe_dump(data_yaml, sort_keys=False, allow_unicode=True))
        return {"split_counts": split_counts, "data_yaml": data_yaml}

    output_path = final_dir() / "data.yaml"
    header = (
        "# Generated by scripts/build/generate_yaml.py (Stage 5.9).\n"
        "# Matches config/classes.yaml's schema exactly (nc, name order).\n"
        "# No 'path' key on purpose — ultralytics resolves train/val/test\n"
        "# relative to THIS file's own directory only when 'path' is absent\n"
        "# (falls through to its own Path(yaml_file).parent logic). Training\n"
        "# runs on RunPod (cloud GPU), not this machine, so this must not\n"
        "# depend on the invoking process's CWD.\n"
    )
    with output_path.open("w", encoding="utf-8") as fh:
        fh.write(header)
        yaml.safe_dump(data_yaml, fh, sort_keys=False, allow_unicode=True)

    print(f"\nWritten to {output_path}")
    return {"split_counts": split_counts, "data_yaml": data_yaml, "output_path": str(output_path)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Print without writing the file.")
    args = parser.parse_args()

    print("=" * 60)
    print("generate_yaml.py — Stage 5.9")
    print("=" * 60)
    print("\nChecking dataset/final/ split contents...")

    run(dry_run=args.dry_run)


if __name__ == "__main__":
    main()
